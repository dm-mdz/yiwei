pub fn usage_from_mac(keycode: u16) -> Option<u16> { KEYS.iter().find(|k| k.1 == keycode && k.1 != NONE).map(|k| k.0) }
pub fn mac_from_usage(usage: u16) -> Option<u16> { KEYS.iter().find(|k| k.0 == usage && k.1 != NONE).map(|k| k.1) }

/// Windows：扫描码和“是不是扩展键”
pub fn usage_from_win(scancode: u16, extended: bool) -> Option<u16> {
    let v = (scancode & 0xFF) | if extended { E } else { 0 };
    KEYS.iter().find(|k| k.2 == v).map(|k| k.0)
}
pub fn win_from_usage(usage: u16) -> Option<(u16, bool)> {
    KEYS.iter().find(|k| k.0 == usage && k.2 != NONE).map(|k| (k.2 & 0xFF, k.2 & E != 0))
}

/// 修饰键的位：消息里的 mods 用这几位
pub const MOD_SHIFT: u32 = 1;
pub const MOD_CTRL: u32 = 2;
pub const MOD_ALT: u32 = 4;      // Mac 上是 Option
pub const MOD_GUI: u32 = 8;      // Mac 上是 Command，Windows 上是 Win 键
pub const MOD_CAPS: u32 = 16;
/// 不是修饰键，借“穿过来”时带修饰键的那个数捎一句话：我（来控制你的这台）开着“鼠标被控切回”，你那边自己的鼠标一动就请我回去
pub const ASK_TAKE_BACK: u32 = 32;

/// 这个键位是哪个修饰键（不是修饰键返回 0）
pub fn modifier_bit(usage: u16) -> u32 {
    match usage { 0xE1 | 0xE5 => MOD_SHIFT, 0xE0 | 0xE4 => MOD_CTRL, 0xE2 | 0xE6 => MOD_ALT, 0xE3 | 0xE7 => MOD_GUI, _ => 0 }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn 表里没有重复的编号() {
        let mut usage = HashSet::new(); let mut mac = HashSet::new(); let mut win = HashSet::new();
        for k in KEYS {
            assert!(usage.insert(k.0), "USB 键位 {:#x} 重复", k.0);
            if k.1 != NONE { assert!(mac.insert(k.1), "macOS 键码 {:#x} 重复", k.1) }
            if k.2 != NONE { assert!(win.insert(k.2), "Windows 扫描码 {:#x} 重复", k.2) }
        }
    }

    #[test]
    fn 每个键来回换一圈还是它() {
        for k in KEYS {
            assert_eq!(mac_from_usage(k.0).and_then(usage_from_mac), Some(k.0));
            let (sc, ext) = win_from_usage(k.0).unwrap();
            assert_eq!(usage_from_win(sc, ext), Some(k.0));
        }
    }

    #[test]
    fn 几个容易弄错的键() {
        assert_eq!(usage_from_mac(0x00), Some(0x04));                 // A
        assert_eq!(win_from_usage(0x04), Some((0x1E, false)));
        assert_eq!(usage_from_mac(0x37), Some(0xE3));                 // 左 Command -> 左 Win
        assert_eq!(win_from_usage(0xE3), Some((0x5B, true)));
        assert_eq!(usage_from_win(0x38, true), Some(0xE6));           // 右 Alt -> 右 Option
        assert_eq!(mac_from_usage(0xE6), Some(0x3D));
        assert_eq!(usage_from_win(0x1C, false), Some(0x28));          // 主键盘回车
        assert_eq!(usage_from_win(0x1C, true), Some(0x58));           // 小键盘回车
        assert_eq!(usage_from_win(0x4B, true), Some(0x50));           // 左方向键
        assert_eq!(usage_from_win(0x4B, false), Some(0x5C));          // 小键盘 4
        assert_eq!(mac_from_usage(0x50), Some(0x7B));
        assert_eq!(usage_from_mac(0xFF), None);
        assert_eq!(modifier_bit(0xE5), MOD_SHIFT);
        assert_eq!(modifier_bit(0x04), 0);
    }
}
